CREATE TABLE IF NOT EXISTS users (
 id VARCHAR(36) PRIMARY KEY, email VARCHAR(160) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL,
 password VARCHAR(200) NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'customer', created_at BIGINT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 token_hash VARCHAR(64) PRIMARY KEY, user_id VARCHAR(36) NOT NULL, csrf VARCHAR(64) NOT NULL, expires_at BIGINT NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS services (
 id VARCHAR(80) PRIMARY KEY, title VARCHAR(120) NOT NULL, english VARCHAR(160) NOT NULL, category VARCHAR(80) NOT NULL,
 description TEXT NOT NULL, price INT NOT NULL, deposit INT NOT NULL, duration VARCHAR(120) NOT NULL,
 features TEXT NOT NULL, image VARCHAR(300) NOT NULL, active TINYINT NOT NULL DEFAULT 1,
 featured TINYINT NOT NULL DEFAULT 0, sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (setting_key VARCHAR(80) PRIMARY KEY, value LONGTEXT NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS bookings (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL, service_id VARCHAR(80) NOT NULL,
 service_title VARCHAR(120) NOT NULL, price INT NOT NULL, deposit INT NOT NULL,
 day VARCHAR(10) NOT NULL, time VARCHAR(5) NOT NULL, contact_name VARCHAR(120) NOT NULL, phone VARCHAR(40) NOT NULL,
 note TEXT NOT NULL, status VARCHAR(24) NOT NULL DEFAULT 'pending', created_at BIGINT NOT NULL,
 expires_at BIGINT NOT NULL, paid_at BIGINT, request_key VARCHAR(36) NOT NULL,
 UNIQUE(user_id,request_key), INDEX booking_slot(day,time,status), INDEX booking_owner(user_id,created_at),
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(service_id) REFERENCES services(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS payments (
 id VARCHAR(80) PRIMARY KEY, booking_id VARCHAR(36) NOT NULL UNIQUE, amount INT NOT NULL,
 method VARCHAR(20) NOT NULL, pid VARCHAR(40) NOT NULL, secret TEXT NOT NULL, gateway VARCHAR(300) NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'pending', trade_no VARCHAR(100) UNIQUE, created_at BIGINT NOT NULL, paid_at BIGINT,
 FOREIGN KEY(booking_id) REFERENCES bookings(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS conversations (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL, booking_id VARCHAR(36) UNIQUE, created_at BIGINT NOT NULL,
 general_user_id VARCHAR(36) GENERATED ALWAYS AS (IF(booking_id IS NULL,user_id,NULL)) STORED UNIQUE,
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(booking_id) REFERENCES bookings(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS messages (
 seq BIGINT UNSIGNED AUTO_INCREMENT UNIQUE, id VARCHAR(36) PRIMARY KEY, conversation_id VARCHAR(36) NOT NULL,
 sender_id VARCHAR(36) NOT NULL, body TEXT NOT NULL, created_at BIGINT NOT NULL,
 INDEX message_thread(conversation_id,created_at,seq),
 FOREIGN KEY(conversation_id) REFERENCES conversations(id) ON DELETE CASCADE, FOREIGN KEY(sender_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS posts (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL, title VARCHAR(200) NOT NULL,
 body TEXT NOT NULL, category VARCHAR(80) NOT NULL, hidden TINYINT NOT NULL DEFAULT 0, created_at BIGINT NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS comments (
 id VARCHAR(36) PRIMARY KEY, post_id VARCHAR(36) NOT NULL, user_id VARCHAR(36) NOT NULL, body TEXT NOT NULL, created_at BIGINT NOT NULL,
 FOREIGN KEY(post_id) REFERENCES posts(id) ON DELETE CASCADE, FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS likes (
 post_id VARCHAR(36) NOT NULL, user_id VARCHAR(36) NOT NULL, PRIMARY KEY(post_id,user_id),
 FOREIGN KEY(post_id) REFERENCES posts(id) ON DELETE CASCADE, FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_logs (
 id VARCHAR(36) PRIMARY KEY, actor_id VARCHAR(80) NOT NULL, action VARCHAR(80) NOT NULL, target VARCHAR(120) NOT NULL, created_at BIGINT NOT NULL
) ENGINE=InnoDB;
